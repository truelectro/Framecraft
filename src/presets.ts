export function resolvePlatformSlot(
  presetId: StorePresetId,
  useCustomSize: boolean,
  width: number,
  height: number
): PlatformSlot {
  if (useCustomSize) {
    return width > height * 1.15 ? 'banner' : 'ios';
  }
  const found = STORE_PRESETS.find((p) => p.id === presetId);
  return found ? found.platformSlot : 'ios';
}

